def cloud(x, y, w, h, r=7):
    pts = []
    perim = 2 * (w + h)
    n = max(8, int(perim / (2 * r)))
    step = perim / n
    def at(d):
        d %= perim
        if d < w:
            return x + d, y
        d -= w
        if d < h:
            return x + w, y + d
        d -= h
        if d < w:
            return x + w - d, y + h
        d -= w
        return x, y + h - d
    start = at(0)
    path = [f"M{start[0]:.1f},{start[1]:.1f}"]
    for i in range(1, n + 1):
        q = at(i * step)
        path.append(f"A{r},{r} 0 0 1 {q[0]:.1f},{q[1]:.1f}")
    return f'<path d="{" ".join(path)}" class="cloud"/>'


