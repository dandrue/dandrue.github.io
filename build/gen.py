COS = math.cos(math.radians(30))
SIN = 0.5

# Piping services (colour, abbreviation, insulation) live in services.json
SERVICES = json.loads((Path(__file__).parent / "services.json").read_text(encoding="utf-8"))
SVC = {s["id"]: s for g in SERVICES["groups"] for s in g["services"]}

C = {sid: f"var(--{sid})" for sid in SVC}
C.update({
    "storm": "var(--sd)",
    "grey": "var(--greywater)",
    "reuse": "var(--reclaim)",
})
INSULATED = {C[sid] for sid, s in SVC.items() if s["insulated"]}


def service_tokens():
    return "\n".join(f"    --{sid}: {s['color']};" for sid, s in SVC.items())


def service_key():
    cols = []
    for g in SERVICES["groups"]:
        items = []
        for s in g["services"]:
            cls = "svc-swatch is-insulated" if s["insulated"] else "svc-swatch"
            items.append(
                f'<li><span class="{cls}" style="--c:var(--{s["id"]})"></span>'
                f'<span class="svc-abbr">{s["abbr"]}</span>'
                f'<span class="svc-name">{_html.escape(s["name"])}</span></li>')
        cols.append(f'<div><h4>{_html.escape(g["name"])}</h4><ul>{"".join(items)}</ul></div>')
    return '<div class="svc-key">' + "".join(cols) + "</div>"


def services_js():
    data = {sid: {"abbr": s["abbr"], "name": s["name"], "color": s["color"], "insulated": s["insulated"]}
            for sid, s in SVC.items()}
    body = json.dumps(data, indent=2)
    return ("// Generated by build/gen.py from build/services.json. Edit that file, not this one.\n"
            f"export const SERVICES = {body};\n")


def iso(ox, oy, s):
    def p(x, y, z):
        return (ox + (x - y) * COS * s, oy + (x + y) * SIN * s - z * s)
    return p


def fmt(pt):
    return f"{pt[0]:.1f},{pt[1]:.1f}"


def poly(pts, cls="", extra=""):
    return f'<polygon class="{cls}" points="{" ".join(fmt(q) for q in pts)}" {extra}/>'


def pipe(pts, color, width=3.4, cls="pipe", delay=None, draw=True, jacket=None):
    """A pipe run. Insulated services get a translucent jacket (80% transparent) under the line."""
    d = "M" + " L".join(fmt(q) for q in pts)
    anim = ""
    if draw:
        anim = f' pathLength="1" class="{cls} draw" style="--d:{delay or 0}s"'
    else:
        anim = f' class="{cls}"'
    out = ""
    if jacket is None:
        jacket = color in INSULATED
    if jacket:
        out = f'<path d="{d}" stroke="{color}" stroke-width="{width * 2.8:.1f}" stroke-opacity="0.2"{anim}/>'
    return out + f'<path d="{d}" stroke="{color}" stroke-width="{width}"{anim}/>'


def text(x, y, s, cls="lbl", anchor="start", extra=""):
    return f'<text x="{x:.1f}" y="{y:.1f}" class="{cls}" text-anchor="{anchor}" {extra}>{s}</text>'


def box_faces(p, x0, x1, y0, y1, z0, z1, cls_top, cls_side, cls_front):
    top = [p(x0, y0, z1), p(x1, y0, z1), p(x1, y1, z1), p(x0, y1, z1)]
    front_y = [p(x0, y1, z1), p(x1, y1, z1), p(x1, y1, z0), p(x0, y1, z0)]
    side_x = [p(x1, y0, z1), p(x1, y1, z1), p(x1, y1, z0), p(x1, y0, z0)]
    return poly(top, cls_top) + poly(front_y, cls_front) + poly(side_x, cls_side)


